// Generates the static assets the site loads: fonts, icon sprite, question data.
// Run: node tools/build-assets.js   (after `npm install`)
const fs = require("node:fs");
const path = require("node:path");

const root = path.join(__dirname, "..");
const read = (p) => fs.readFileSync(path.join(root, p), "utf8");
const write = (p, s) => fs.writeFileSync(path.join(root, p), s);

// 1. Fonts: only the weights and subsets the UI uses.
const fontSrc = path.join(root, "node_modules/@fontsource/be-vietnam-pro/files");
const weights = [400, 500, 600, 700];
const subsets = ["latin", "vietnamese"];
for (const w of weights) {
  for (const s of subsets) {
    const f = `be-vietnam-pro-${s}-${w}-normal.woff2`;
    fs.copyFileSync(path.join(fontSrc, f), path.join(root, "assets/fonts", f));
  }
}

// 2. Icons: Phosphor SVGs inlined as strings, keyed by name.
const ICONS = {
  cpu: "regular/cpu",
  desktop: "regular/desktop",
  fileText: "regular/file-text",
  table: "regular/table",
  presentation: "regular/presentation-chart",
  globe: "regular/globe",
  sun: "regular/sun",
  moon: "regular/moon",
  check: "bold/check",
  x: "bold/x",
  checkFill: "fill/check-circle",
  xFill: "fill/x-circle",
  arrowLeft: "regular/arrow-left",
  arrowRight: "regular/arrow-right",
  timer: "regular/timer",
  redo: "regular/arrow-counter-clockwise",
  trash: "regular/trash",
  play: "fill/play",
  exam: "regular/exam",
  listNumbers: "regular/list-numbers",
  warning: "regular/warning-circle",
  caretDown: "regular/caret-down",
  signOut: "regular/sign-out",
  trophy: "regular/trophy",
};
const iconDir = path.join(root, "node_modules/@phosphor-icons/core/assets");
const sprite = {};
for (const [name, rel] of Object.entries(ICONS)) {
  const [weight, base] = rel.split("/");
  const file = weight === "regular" ? `${base}.svg` : `${base}-${weight}.svg`;
  const svg = fs.readFileSync(path.join(iconDir, weight, file), "utf8").trim();
  sprite[name] = svg.replace("<svg ", '<svg aria-hidden="true" focusable="false" ');
}
write(
  "js/icons.js",
  `// Generated by tools/build-assets.js from @phosphor-icons/core. Do not edit.\nwindow.ICONS = ${JSON.stringify(sprite, null, 1)};\n`
);

// 3. Question data from the parsed PDFs.
const data = JSON.parse(read("data/questions.json"));
write(
  "data/questions.js",
  `// Generated by tools/build-assets.js from data/questions.json. Do not edit.\nwindow.QUESTION_DATA = ${JSON.stringify(data)};\n`
);
console.log("assets built:", data.reduce((n, m) => n + m.questions.length, 0), "questions");
